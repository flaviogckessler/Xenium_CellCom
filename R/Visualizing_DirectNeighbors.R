#However, this visualization is not ideal for representing physical contact between neighboring cells because the edges generated by `geom_edgespace()` connect the centroids of adjacent cells.
#Cell boundaries can be irregular, and neighboring cells can differ substantially in size. Moreover, some cells share only a small portion of their boundaries (cell membranes). Consequently, edges connecting cell centroids may extend beyond the boundaries of the corresponding cell pair or pass through regions not occupied by either cell.
######################################
# To identify a point within the contact region between two neighboring cells, we first buffer both cell polygons by the `proximity_threshold` distance and compute their intersection using `sf::st_intersection()`. We then use `sf::st_point_on_surface()` to obtain a representative point within the resulting intersection geometry.
gs_neig2 <- cropGraphSpace(gs_neig, 
                           xmin = 0.45, xmax = 0.6, 
                           ymin = 0.2, ymax = 0.35)

# However, when the cropped GraphSpace object is re-normalized using the normalizeGraphsSpace() function, the proximity_threshold parameter must also be rescaled. The rescaling factor can be calculated by comparing the area of the cropped region before and after normalization.
before <- sf::st_as_sf(gs_neig2[["nodes"]])

# With the GraphSpace nodes available in their pre-normalized coordinates, we can proceed with the re-normalization step:
gs_neig2 <- normalizeGraphSpace(gs_neig2, mar = 0, norm.geometry = TRUE)

# Now, we can also retrieve the GraphSpace nodes after re-normalization.
after  <- sf::st_as_sf(gs_neig2[["nodes"]])
before <- before[match(after$name, before$name), ]

# Using the areas of the GraphSpace nodes before and after re-normalization, we can calculate their ratio:
area_ratio <- as.numeric(sf::st_area(after) / sf::st_area(before))
# Using the area ratio, we can rescale the `proximity_threshold` parameter to match the normalized spatial coordinates of the cropped region.
proximity_threshold_zoom <- proximity_threshold * median(sqrt(area_ratio))

proximity_threshold_zoom/proximity_threshold
# 6.920188
# The proximity_threshold parameter was multiplied by a scaling factor of approximately 6.92 (~7) to match the normalized spatial coordinates of the cropped region.

# Clear 'before' and 'after' datasets
rm(before,after)

gs_edge_attr(gs_neig2, "intersect_point") <- 
  st_intersection(gs_neig2[["nodes"]][gs_neig2[["edges"]]$name1,]$geometry %>% 
                    sf::st_buffer(dist=proximity_threshold_zoom),
                  gs_neig2[["nodes"]][gs_neig2[["edges"]]$name2,]$geometry %>% 
                    sf::st_buffer(dist=proximity_threshold_zoom),
                  by_element=TRUE) %>%
  st_point_on_surface()


